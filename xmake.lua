add_rules("mode.debug", "mode.release")

package("e2fsprogs")
    set_sourcedir("e2fsprogs")
    on_install(function (package)
        local configs = {}
		import("package.tools.autoconf").install(package, configs)
    end)
package_end()

package("xwidget")
    set_sourcedir("../xwidget")
    on_install(function (package)
		import("package.tools.xmake").install(package)
    end)
package_end()


add_requires("e2fsprogs", "xwidget", "freetype", "libpng", "sdl2")

target("libext2fm")
	set_basename("ext2fm")
    set_kind("shared")
	add_packages("e2fsprogs")
	add_includedirs("include", "e2fsprogs/lib", "e2fsprogs/lib/ext2fs", "src")
    add_files("src/*.c")
target_end()

target("ext2fm")
	set_kind("binary")
	add_includedirs("include")
	add_deps("libext2fm")
	add_files("console/main.c")
target_end()

target("xfinder")
    set_kind("binary")
    add_packages("xwidget", "freetype", "sdl2")
	add_includedirs("xfinder/include")
	add_cxflags("-Wno-implicit-function-declaration","-Wno-c++11-narrowing", {public = true})
    add_files("xfinder/**.cc")
	add_rpathdirs("@loader_path")
    after_build(function (target)
        os.cp("xfinder/res", target:targetdir())
    end)
target_end()
